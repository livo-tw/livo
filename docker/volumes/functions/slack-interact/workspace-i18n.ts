export type WorkspaceLocale = 'zh-TW' | 'zh-CN' | 'en';
export const WORKSPACE_MESSAGES: Record<WorkspaceLocale, Record<string, string>> = {
  'zh-TW': Object.fromEntries(Object.keys(translations).map(key => [key, key])),
  'zh-CN': Object.fromEntries(Object.entries(translations).map(([key, values]) => [key, values[0]])),
  en: Object.fromEntries(Object.entries(translations).map(([key, values]) => [key, values[1]])),
};

/** Interpolate only known copy keys. Never run character conversion or replacement over user content. */
export function workspaceText(value: string, locale = 'zh-TW', variables: Record<string, string | number> = {}): string {
  const normalized = String(locale).replace(/_/g, '-').toLowerCase();
  const selected: WorkspaceLocale = normalized.startsWith('en') ? 'en'
    : /^zh-(?:cn|sg|hans)(?:-|$)/.test(normalized) ? 'zh-CN' : 'zh-TW';
  if (!Object.prototype.hasOwnProperty.call(WORKSPACE_MESSAGES[selected], value)) return value;
  return WORKSPACE_MESSAGES[selected][value].replace(/\{(\w+)\}/g,
    (placeholder, name: string) => Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : placeholder);
}
